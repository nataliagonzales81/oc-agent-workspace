func TestInspectAbsentFileCreates(t *testing.T) {
	l := managedLayout(t)
	got, err := l.Inspect(l.KnowledgeIndex(), false)
	if err != nil {
		t.Fatalf("Inspect: %v", err)
	}
	if got.Action != ActionCreate || got.Exists {
		t.Errorf("target = %+v, want a create", got)
	}
	if got.Rel != filepath.Join(AgentDir, "knowledge", "index.yaml") {
		t.Errorf("Rel = %q, want the project-relative path", got.Rel)
	}
}

// An existing but empty file has nothing to lose, so it is written even without
// --force. This keeps a half-finished init resumable.
func TestInspectEmptyFileOverwritesWithoutForce(t *testing.T) {
	l := newLayout(t)
	writeFile(t, l.RulesMD(), "")

	got, err := l.Inspect(l.RulesMD(), false)
	if err != nil {
		t.Fatalf("Inspect: %v", err)
	}
	if got.Action != ActionOverwrite {
		t.Errorf("action = %q, want %q", got.Action, ActionOverwrite)
	}
	if got.NonEmpty {
		t.Error("NonEmpty = true for a zero-byte file")
	}
}

