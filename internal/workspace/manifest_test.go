func TestInspectAllAndTheSelectionHelpers(t *testing.T) {
	l := managedLayout(t)
	writeFile(t, l.RulesMD(), "keep me\n")
	writeFile(t, l.SkillFile("s"), "keep me too\n")

	targets, err := l.InspectAll(l.Files(), false)
	if err != nil {
		t.Fatalf("InspectAll: %v", err)
	}
	if len(targets) != len(l.Files()) {
		t.Fatalf("got %d targets, want %d", len(targets), len(l.Files()))
	}
	kept := Kept(targets)
	if len(kept) != 2 {
		t.Fatalf("Kept = %+v, want agent.yaml and RULES.md", kept)
	}
	for _, want := range []string{l.AgentYAML(), l.RulesMD()} {
		found := false
		for _, k := range kept {
			if k.Path == want {
				found = true
			}
		}
		if !found {
			t.Errorf("Kept is missing %q", want)
		}
	}
	if len(Refused(targets)) != 0 {
		t.Errorf("Refused = %v, want none without --force", Refused(targets))
	}

	forced, err := l.InspectAll([]string{l.RulesMD(), l.SkillFile("s")}, true)
	if err != nil {
		t.Fatalf("InspectAll with force: %v", err)
	}
	refused := Refused(forced)
	if len(refused) != 1 || refused[0].Path != l.SkillFile("s") {
		t.Errorf("Refused = %+v, want just the skill file", refused)
	}
}

