func TestOcawManifestErrors(t *testing.T) {
	t.Run("missing", func(t *testing.T) {
		l := newLayout(t)
		if code := codeOf(t, mustErr(l.OcawManifest())); code != envelope.CodeWorkspaceMissing {
			t.Errorf("code = %s, want %s", code, envelope.CodeWorkspaceMissing)
		}
	})
	t.Run("garbage", func(t *testing.T) {
		l := newLayout(t)
		writeFile(t, l.AgentYAML(), "ocaw: true\n\tnope\n")
		if code := codeOf(t, mustErr(l.OcawManifest())); code != envelope.CodeValidationFailed {
			t.Errorf("code = %s, want %s", code, envelope.CodeValidationFailed)
		}
	})
	t.Run("wrong_schema", func(t *testing.T) {
		l := newLayout(t)
		writeFile(t, l.AgentYAML(), "ocaw: true\nschema: ocaw/agent@99\nname: x\nproject:\n  type: go\n")
		err := mustErr(l.OcawManifest())
		if codeOf(t, err) != envelope.CodeValidationFailed {
			t.Errorf("code = %s, want %s", codeOf(t, err), envelope.CodeValidationFailed)
		}
		if !strings.Contains(err.Error(), "ocaw/agent@1") {
			t.Errorf("error = %q, want it to name the schema this build writes", err)
		}
	})
}

func mustErr[T any](_ T, err error) error { return err }
